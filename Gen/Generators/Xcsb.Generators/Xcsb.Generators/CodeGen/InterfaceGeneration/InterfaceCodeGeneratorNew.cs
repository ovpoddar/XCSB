using System.Text;
using Microsoft.CodeAnalysis;

namespace Xcsb.Generators.CodeGen.InterfaceGeneration;

internal static class InterfaceCodeGeneratorNew
{
    internal static StringBuilder Generate(INamedTypeSymbol symbol, DeclarationKind type)
    {
        var result = new StringBuilder();
        result.AppendLine("// <auto-generated/>");
        result.AppendLine();

        if (type.HasFlag(DeclarationKind.Checked))
            result.Append(InterfaceCodeGenerator.Generate(symbol, interfaceSuffix: "Checked", methodSuffix: "Checked", returnTypeProvider: _ => "void"));
        if (type.HasFlag(DeclarationKind.Unchecked))
            result.Append(InterfaceCodeGenerator.Generate(symbol, interfaceSuffix: "Unchecked", methodSuffix: "Unchecked", returnTypeProvider: _ => "void"));
        if (type.HasFlag(DeclarationKind.Buffer))
            result.Append(InterfaceCodeGenerator.Generate(symbol, interfaceSuffix: "Buffer", methodSuffix: "Buffer", returnTypeProvider: _ => "void"));
        
        return result;
    }
}