using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Diagnostics;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Xcsb.Generators.CodeGen.ClassGeneration;

internal static class ClassCodeGenerator
{
    internal static StringBuilder Generate(INamedTypeSymbol classSymbol,
        List<(ImplementationKind, INamedTypeSymbol)> collection)
    {
        var result = new StringBuilder();
        result.AppendLine("// <auto-generated/>");
        result.AppendLine("using Xcsb.Connection.Helpers;");
        result.AppendLine();
        if (!classSymbol.ContainingNamespace.IsGlobalNamespace)
            result.AppendLine($"namespace {classSymbol.ContainingNamespace.ToDisplayString()}");
        result.AppendLine("{");


        foreach (var (kindInfo, interfaceSymbol) in collection)
        {
            if (kindInfo.HasFlag(ImplementationKind.Checked))
                Generate(result, classSymbol, interfaceSymbol, "Checked", (sb, method) =>
                {
                    sb.AppendLine();
                    sb.AppendLine("        {");
                    sb.Append("            var cookie = this.")
                        .Append(method.Name)
                        .Append("Base(");

                    for (var i = 0; i < method.Parameters.Length; i++)
                    {
                        var param = method.Parameters[i];
                        if (i > 0) sb.Append(", ");
                        sb.Append(param.Name);
                    }

                    sb.AppendLine(");");
                    sb.AppendLine("            _socketAccessor.SkipErrorForSequence(cookie.Id, true);");
                    sb.AppendLine("        }");
                });
            if (kindInfo.HasFlag(ImplementationKind.Unchecked))
                Generate(result, classSymbol, interfaceSymbol, "Unchecked", (sb, method) =>
                {
                    sb.AppendLine();
                    sb.AppendLine("        {");
                    sb.Append("            var cookie = this.")
                        .Append(method.Name)
                        .Append("Base(");

                    for (var i = 0; i < method.Parameters.Length; i++)
                    {
                        var param = method.Parameters[i];
                        if (i > 0) sb.Append(", ");
                        sb.Append(param.Name);
                    }

                    sb.AppendLine(");");
                    sb.AppendLine("            _socketAccessor.SkipErrorForSequence(cookie.Id, false);");
                    sb.AppendLine("        }");
                });

            if (kindInfo.HasFlag(ImplementationKind.Base))
                Generate(result, classSymbol, interfaceSymbol, string.Empty, (sb, method) =>
                    {
                        sb.AppendLine(" =>");
                        sb.Append("            this.")
                            .Append(method.Name)
                            .Append("Base(");
                        for (var i = 0; i < method.Parameters.Length; i++)
                        {
                            var param = method.Parameters[i];
                            if (i > 0) sb.Append(", ");
                            sb.Append(param.Name);
                        }

                        sb.AppendLine(");");
                    },
                    followReturnType: true);

            if (kindInfo.HasFlag(ImplementationKind.Return))
                Generate(result, classSymbol, interfaceSymbol, string.Empty, (sb, method) =>
                    {
                        sb.AppendLine();
                        sb.AppendLine("        {");

                        var helpfulSymbol = GetWorkingSymbolOfReturnType(method);
                        if (helpfulSymbol.Length == 0)
                        {
                            sb.Append("            return ")
                                .Append(method.Name)
                                .Append("Override(");
                            for (var i = 0; i < method.Parameters.Length; i++)
                            {
                                var param = method.Parameters[i];
                                if (i > 0) sb.Append(", ");
                                sb.Append(param.Name);
                            }
                            sb.AppendLine(");");
                            sb.AppendLine("        }");
                            return;
                        }
                        
                        sb.Append("            var cookie = this.")
                            .Append(method.Name)
                            .Append("Base(");
                        for (var i = 0; i < method.Parameters.Length; i++)
                        {
                            var param = method.Parameters[i];
                            if (i > 0) sb.Append(", ");
                            sb.Append(param.Name);
                        }
                        sb.AppendLine(");");
                        sb.Append(
                            "            var (result, mapping) = this._socketAccessor.SocketIn.ReceivedResponseSpan<")
                            .Append(string.Join(", ", helpfulSymbol))
                            .AppendLine(">(cookie.Id);");
                        
                        sb.AppendLine("            if (mapping.ResponseType == Xcsb.Connection.Response.Contract.XResponseType.Reply)");
                        sb.Append("                return new Xcsb.Connection.Models.ReplyLease<");
                        sb.Append(helpfulSymbol[0]);
                        sb.AppendLine(">(result, this._socketAccessor.SocketIn.BufferPool);");
                        sb.AppendLine("            var error = result.ToStruct<Xcsb.Connection.Response.Contract.XResponse>();");
                        sb.AppendLine("            this._socketAccessor.SocketIn.BufferPool.Return(result);");
                        sb.AppendLine("            throw new Xcsb.Connection.Infrastructure.Exceptions.XEventException(new Xcsb.Connection.Response.Contract.GenericError(error, mapping.ErrorMessageAction!));");
                        sb.AppendLine("        }");
                    },
                    followReturnType: true);

            if (kindInfo.HasFlag(ImplementationKind.Async))
                Generate(result, classSymbol, interfaceSymbol, "Async", (sb, method) =>
                {
                    
                      sb.AppendLine();
                       sb.AppendLine("        {");

                       var helpfulSymbol = GetWorkingSymbolOfReturnType(method);
                       if (helpfulSymbol.Length == 0)
                       {
                           sb.Append("            return await ")
                               .Append(method.Name)
                               .Append("OverrideAsync(");
                           for (var i = 0; i < method.Parameters.Length; i++)
                           {
                               var param = method.Parameters[i];
                               if (i > 0) sb.Append(", ");
                               sb.Append(param.Name);
                           }
                           sb.AppendLine(");");
                           sb.AppendLine("        }");
                           return;
                       }
                       
                       sb.Append("            var cookie = this.")
                           .Append(method.Name)
                           .Append("Base(");
                       for (var i = 0; i < method.Parameters.Length; i++)
                       {
                           var param = method.Parameters[i];
                           if (i > 0) sb.Append(", ");
                           sb.Append(param.Name)
                               .Append(param.Type.Name.Contains("Span") ? ".Span" : "");
                       }
                       sb.AppendLine(");");
                       sb.Append(
                           "            var (result, mapping) = await this._socketAccessor.SocketIn.ReceivedResponseSpanAsync<")
                           .Append(string.Join(", ", helpfulSymbol))
                           .AppendLine(">(cookie.Id, token).ConfigureAwait(false);");
                       
                       sb.AppendLine("            if (mapping.ResponseType == Xcsb.Connection.Response.Contract.XResponseType.Reply)");
                       sb.Append("                return new Xcsb.Connection.Models.ReplyLease<");
                       sb.Append(helpfulSymbol[0]);
                       sb.AppendLine(">(result, this._socketAccessor.SocketIn.BufferPool);");
                       sb.AppendLine("            var error = result.ToStruct<Xcsb.Connection.Response.Contract.XResponse>();");
                       sb.AppendLine("            this._socketAccessor.SocketIn.BufferPool.Return(result);");
                       sb.AppendLine("            throw new Xcsb.Connection.Infrastructure.Exceptions.XEventException(new Xcsb.Connection.Response.Contract.GenericError(error, mapping.ErrorMessageAction!));");

                       sb.AppendLine("        }");
                    
                    
                }, followReturnType: true, addCancellationToken: true);
        }

        result.AppendLine("}");
        return result;
    }

    private static ImmutableArray<ITypeSymbol> GetWorkingSymbolOfReturnType(IMethodSymbol returnType)
    {
        if (returnType.ReturnType is not INamedTypeSymbol symbol || symbol.TypeArguments.Length == 0)
            return ImmutableArray<ITypeSymbol>.Empty;

        var replySymbol = symbol.TypeArguments.FirstOrDefault(a => a.IsValueType) as INamedTypeSymbol;
        if (replySymbol == null)
            return ImmutableArray<ITypeSymbol>.Empty;

        var targetInterface =
            replySymbol.AllInterfaces.FirstOrDefault(a =>
                a.Name == "IXReply" && a.ContainingNamespace.ToDisplayString() == "Xcsb.Connection.Response.Contract" &&
                a.TypeArguments.Length > 0
            );
        return targetInterface?.TypeArguments ?? ImmutableArray<ITypeSymbol>.Empty;
    }

    private static void Generate(
        StringBuilder sb,
        INamedTypeSymbol classSymbol,
        INamedTypeSymbol interfaceSymbol,
        string methodSuffix,
        Action<StringBuilder, IMethodSymbol> writeMethodBody,
        bool addCancellationToken = false,
        bool followReturnType = false)
    {
        sb.AppendLine($"    {classSymbol.DeclaredAccessibility.ToString().ToLower()} partial class {classSymbol.Name}");
        sb.AppendLine("    {");

        foreach (var method in interfaceSymbol.GetMembers().OfType<IMethodSymbol>())
        {
            if (method.MethodKind != MethodKind.Ordinary) continue;
            sb.Append("        public ")
                .Append(addCancellationToken ? "async global::System.Threading.Tasks.ValueTask<" : "")
                .Append(followReturnType
                    ? method.ReturnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                    : "void")
                .Append(addCancellationToken ? ">" : "")
                .Append(" ");

            sb.Append(method.Name)
                .Append(methodSuffix);

            if (method.TypeParameters.Length > 0)
            {
                sb.Append('<');
                sb.Append(string.Join(", ", method.TypeParameters.Select(tp => tp.Name)));
                sb.Append('>');
            }

            sb.Append("(");
            for (var i = 0; i < method.Parameters.Length; i++)
            {
                var param = method.Parameters[i];
                if (i > 0) sb.Append(", ");
                sb.Append(OptimizeType(param.Type, addCancellationToken))
                    .Append(" ").Append(param.Name);
                if (param.HasExplicitDefaultValue) sb.Append(" = ").Append(param.ExplicitDefaultValue);
            }

            if (addCancellationToken && method.Parameters.Length != 0) sb.Append(", ");
            if (addCancellationToken)
                sb.Append("System.Threading.CancellationToken token = default");

            sb.Append(")");

            foreach (var tp in method.TypeParameters)
            {
                var parts = new List<string>();
                if (tp.HasReferenceTypeConstraint && !ConstrainPragmaWriter.Contain(method, "class"))
                    parts.Add("class");
                if (tp.HasValueTypeConstraint && !ConstrainPragmaWriter.Contain(method, "struct"))
                    parts.Add("struct");
                if (tp.HasUnmanagedTypeConstraint && !ConstrainPragmaWriter.Contain(method, "unmanaged"))
                    parts.Add("unmanaged");
                foreach (var ct in tp.ConstraintTypes)
                    if (!ConstrainPragmaWriter.Contain(method, ct.ToDisplayString(new SymbolDisplayFormat(
                            typeQualificationStyle: SymbolDisplayTypeQualificationStyle
                                .NameAndContainingTypesAndNamespaces)
                        )))
                        parts.Add(ct.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
                if (tp.HasConstructorConstraint && !ConstrainPragmaWriter.Contain(method, "new()")) parts.Add("new()");


                if (parts.Count <= 0) continue;
                sb.Append(" where ");
                sb.Append(tp.Name);
                sb.Append(" : ");
                sb.Append(string.Join(", ", parts));
            }

            ConstrainPragmaWriter.Write(sb, method, false);
            writeMethodBody(sb, method);
        }

        sb.AppendLine("    }");
    }
    
    
    private static string OptimizeType(ITypeSymbol type, bool async)
    {
        if (type is INamedTypeSymbol { IsGenericType: true } a && a.Name.Contains("ReadOnly"))
        {
            return (async ? "global::System.ReadOnlyMemory<" : "global::System.ReadOnlySpan<")
                   + string.Join(", ",
                       a.TypeArguments.Select(b => b.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)))
                   + ">";
        }

        return type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
    }
}